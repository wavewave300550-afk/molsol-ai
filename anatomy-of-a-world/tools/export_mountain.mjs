// Pre-generate the Migrating Mountain and write the compact data module used in-game.
//   node tools/export_mountain.mjs <out.js>
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, "..");
const S = path.join(ROOT, "build", "scripts");
const gen = await import(pathToFileURL(path.join(S, "gen", "mountain.js")).href);
const codec = await import(pathToFileURL(path.join(S, "gen", "codec.js")).href);

const t0 = Date.now();
const m = new gen.MountainModel().generate();
const g = m.g;
const bytes16 = (a) => new Uint8Array(a.buffer, a.byteOffset, a.byteLength);
const cols = codec.encodeColumns(g.sx, g.sz, g.sy, (cx, cz, cy) => m.grid[(cx * g.sz + cz) * g.sy + cy]);

// Phase 2 cylinder around the heart, for both rib layouts
const D = gen.MM.disk;
const R = D.outerR + 1;
const hx = Math.floor(gen.MM.heart.x);
const hz = Math.floor(gen.MM.heart.z);
const P2 = { x0: hx - R, z0: hz - R, y0: D.mantleY - 6, sx: R * 2 + 1, sz: R * 2 + 1, sy: D.y + 1 - (D.mantleY - 6) };
function p2(layout) {
  // value 0 = outside the cylinder (keep), 1 = air, >= 2 block
  return codec.encodeColumns(P2.sx, P2.sz, P2.sy, (cx, cz, cy) => {
    const b = m.phase2Block(P2.x0 + cx, P2.y0 + cy, P2.z0 + cz, layout);
    return b < 0 ? 0 : b;
  });
}
// the air mask is needed too (the disk carves the old cavern floor): encode air cells as palette 254 marker
function p2WithAir(layout) {
  return codec.encodeColumns(P2.sx, P2.sz, P2.sy, (cx, cz, cy) => {
    const b = m.phase2Block(P2.x0 + cx, P2.y0 + cy, P2.z0 + cz, layout);
    return b < 0 ? 0 : b === 1 ? 255 : b;
  });
}
const data = {
  v: 1,
  seed: m.seed,
  grid: g,
  cols: codec.pack(cols),
  top: codec.pack(bytes16(m.top)),
  under: codec.pack(bytes16(m.under)),
  caveTop: codec.pack(bytes16(m.caveTop)),
  flags: codec.pack(m.flags),
  p2box: P2,
  p2a: codec.pack(p2WithAir(0)),
  p2b: codec.pack(p2WithAir(1)),
  trees: m.trees,
  nodes: m.nodes,
  legs: m.legs,
  waterfalls: m.waterfalls,
  pathPoints: m.pathPoints,
  summit: m.summit,
  tunnelMouth: m.tunnelMouth,
};
void p2;
// round-trip self check
for (const [k, raw] of [["cols", cols], ["flags", m.flags]]) {
  const back = codec.unpack(codec.pack(raw));
  if (back.length !== raw.length || back.some((v, i) => v !== raw[i])) throw new Error("codec round trip failed for " + k);
}
const out = process.argv[2] ?? path.join(S, "bosses", "migrating_mountain", "mm_data.js");
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, "// Generated by tools/export_mountain.mjs - do not edit.\nexport const MM_DATA = " + JSON.stringify(data) + ";\n");
console.log(`mm_data.js: ${(fs.statSync(out).size / 1024).toFixed(0)} KiB (gen ${Date.now() - t0} ms, ${m.trees.length} trees)`);
