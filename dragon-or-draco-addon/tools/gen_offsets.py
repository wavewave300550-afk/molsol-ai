#!/usr/bin/env python3
"""scripts-src/offsets.ts  <- forward kinematics of the real geometry + animation files.

The script must know where the mouth is (fire breath origin, bite reach) and how long each
animation runs.  Instead of hand-typed guesses those numbers are measured here from
red_dragon.geo.json + red_dragon.animation.json with the same kinematics the preview uses,
so the server-side damage and particles line up with what the client draws.

Local offsets are in blocks: fwd (+ = in front of the dragon), up, left (+ = dragon's left).
"""
import json
import math
import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import kinematics as K  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RP = os.path.join(ROOT, "addon", "resource_packs", "dragon_or_draco")
GEO = K.load_json(os.path.join(RP, "models", "entity", "red_dragon.geo.json"))["minecraft:geometry"][0]
ANIMS = K.load_json(os.path.join(RP, "animations", "red_dragon.animation.json"))["animations"]
P = "animation.dod.red_dragon."
# fire_breath sweeps the neck with sin(t*140); sample where the sweep crosses zero
T_FIRE = 180 / 140


def local(p):
    return {"fwd": round(-p[2] / 16, 3), "up": round(p[1] / 16, 3), "left": round(p[0] / 16, 3)}


def mouth(layers, t, aim, extra_env=None):
    env = {"prop:dod:aim": aim, "prop:dod:jet": 12}
    env.update(extra_env or {})
    pose = K.sample_pose([ANIMS[P + n] for n in layers], [1.0] * len(layers), [t] * len(layers), env)
    return K.locator_world(GEO, pose, "head", "mouth")


def main():
    aims = list(range(-40, 61, 10))
    ground = [local(mouth(["idle", "breathe", "fire_breath"], T_FIRE, a)) for a in aims]
    air = []
    for a in aims:
        pts = []
        for k in range(6):
            tf = k / 6 * ANIMS[P + "fly"]["animation_length"]
            env = {"prop:dod:aim": a}
            pose = K.sample_pose([ANIMS[P + "fly"], ANIMS[P + "fire_breath"]], [1, 1], [tf, T_FIRE], env)
            pts.append(K.locator_world(GEO, pose, "head", "mouth"))
        air.append(local(np.mean(pts, axis=0)))
    def head_pitch(layers, times):
        env = {"prop:dod:aim": 0}
        pose = K.sample_pose([ANIMS[P + n] for n in layers], [1.0] * len(layers), times, env)
        M = K.bone_matrices(GEO, pose)["head"]
        f = M[:3, :3] @ np.array([0, 0, -1.0])
        f /= np.linalg.norm(f)
        return math.degrees(math.asin(-f[1]))  # + = nose down

    pitch_ground = head_pitch(["idle", "breathe", "fire_breath"], [T_FIRE] * 3)
    fl = ANIMS[P + "fly"]["animation_length"]
    pitch_air = float(np.mean([head_pitch(["fly", "fire_breath"], [k / 6 * fl, T_FIRE]) for k in range(6)]))
    bite = local(mouth(["idle", "breathe", "bite"], 0.45, 0))
    bite_air = local(mouth(["fly", "bite"], 0.45, 0))
    rest = local(mouth(["idle", "breathe"], 0.0, 0))
    lengths = {k[len(P):]: v["animation_length"] for k, v in ANIMS.items()}
    out = [
        "// GENERATED by tools/gen_offsets.py from the geometry + animation files. Do not edit by hand.",
        "export interface LocalOffset { fwd: number; up: number; left: number }",
        f"export const AIM_STEPS = {json.dumps(aims)};",
        f"export const MOUTH_FIRE_GROUND: LocalOffset[] = {json.dumps(ground)};",
        f"export const MOUTH_FIRE_AIR: LocalOffset[] = {json.dumps(air)};",
        f"export const MOUTH_BITE: LocalOffset = {json.dumps(bite)};",
        f"export const MOUTH_BITE_AIR: LocalOffset = {json.dumps(bite_air)};",
        f"export const MOUTH_REST: LocalOffset = {json.dumps(rest)};",
        "// head pitch (deg, + = down) of the fire pose at dod:aim = 0; the script subtracts it from the wanted pitch",
        f"export const FIRE_PITCH_OFFSET_GROUND = {round(pitch_ground, 2)};",
        f"export const FIRE_PITCH_OFFSET_AIR = {round(pitch_air, 2)};",
        f"export const ANIM_LENGTH: Record<string, number> = {json.dumps(lengths)};",
        "",
    ]
    with open(os.path.join(ROOT, "scripts-src", "offsets.ts"), "w") as f:
        f.write("\n".join(out))
    print("offsets: mouth@aim0 ground", ground[4], "air", air[4], "bite", bite,
          f"pitch offset ground {pitch_ground:.2f} air {pitch_air:.2f}")


if __name__ == "__main__":
    main()
