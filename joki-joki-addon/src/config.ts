export enum Mode {
  Normal = 1,
  Heat = 2,
  Pressure = 3,
  Redline = 4,
}

export interface ModeSpec {
  name: string;
  color: string;
  /** Speed effect amplifier (-1 = none). */
  speed: number;
  /** Strength effect amplifier for melee (-1 = none). Strength adds +3 damage per level. */
  strength: number;
  /** Multiplier on ability damage, knockback and propulsion. */
  power: number;
  /** Multiplier on heat generated by abilities. */
  heatMult: number;
  /** Heat per second while idling in this mode (negative = cooling). */
  idleHeatPerSec: number;
  /** Multiplier applied to ability cooldowns. */
  cooldownMult: number;
  /** Extra knockback added to every melee hit. */
  meleeKnock: number;
}

