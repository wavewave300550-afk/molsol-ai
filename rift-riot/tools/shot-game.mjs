// Dev helper: walks title → select → race on a phone-sized viewport and saves screenshots.
import { loadPlaywright, GL_ARGS } from './_pw.mjs';
const { chromium } = await loadPlaywright();
const out = process.argv[2] || '.';
const racer = process.argv[3] || 'boonsong';
const base = process.env.URL || 'http://localhost:5173';
const portrait = process.argv.includes('portrait');
const b = await chromium.launch({ args: GL_ARGS });
const ctx = await b.newContext({ viewport: portrait ? { width: 390, height: 844 } : { width: 844, height: 390 }, hasTouch: true, isMobile: true, deviceScaleFactor: 1 });
const page = await ctx.newPage();
const errors = [];
page.on('pageerror', (e) => errors.push(String(e)));
page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()); });
await page.goto(base + '/?fps=1' + (process.argv.includes('auto') ? '&autopilot=1' : ''));
await page.waitForFunction('window.__riftriot && window.__riftriot.app.state === "title"', null, { timeout: 60000 });
await page.waitForTimeout(2500);
await page.screenshot({ path: `${out}/g-title.png` });
await page.tap('#btnStart');
await page.waitForTimeout(600);
await page.evaluate((id) => window.__riftriot.selectRacer(id), racer);
await page.waitForTimeout(1200);
await page.screenshot({ path: `${out}/g-select.png` });
await page.tap('#btnRace');
await page.waitForTimeout(2000);
await page.screenshot({ path: `${out}/g-count.png` });
await page.waitForTimeout(6000);
await page.screenshot({ path: `${out}/g-race1.png` });
await page.tap('#btnSkill');
await page.waitForTimeout(900);
await page.screenshot({ path: `${out}/g-skill.png` });
await page.waitForTimeout(6000);
await page.screenshot({ path: `${out}/g-race2.png` });
console.log(JSON.stringify(await page.evaluate(() => { const a = window.__riftriot.app; const p = a.race.player; return { fps: a.fps, pr: a.pr, state: a.state, phase: a.race.phase, t: a.race.time, rank: p.rank, lap: p.lap, speed: p.speed, cd: p.sk.cd, calls: window.__riftriot.renderer.info.render.calls, tris: window.__riftriot.renderer.info.render.triangles }; })));
if (errors.length) console.log('ERRORS:\n' + errors.slice(0, 12).join('\n'));
await b.close();
