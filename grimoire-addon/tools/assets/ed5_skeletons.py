"""ED05 animated fossil skeletons: ed5_skel_nature | ed5_skel_heat | ed5_skel_tide | ed5_skel_air.

Each skeleton is built by ed5_bones.Sk on the SAME rig as its living species (bone names, pivots,
parents, bind rotations), rendered at the species' SCALE, so the living locomotion / attack
animations are reused unchanged (copied, with their sound / particle events remapped to bone
clatter, distant voice echoes and fossil dust).  Own animations: hidden, emerge (peels out of the
slab flat -> full depth, unfolds from the death pose, grows from relief size and lands), return
(folds back into the death pose, shrinks and flattens into the relief) and an always-on 'rattle'.
"""
from __future__ import annotations

from kit.geo import Model

from .ed5_bones import (EMERGE_LEN, LIVING, RETURN_LEN, SPECIES, Mats, Sk, emerge_anim, hidden_anim, rattle_anim, relief,
                        return_anim, reuse)

# state tables (mirrored in src/spells/_ed05_assets.ts, generated by ed5_monument)
STATES = {
    "nature": ["hidden", "emerge", "idle", "move", "attack_a", "attack_b", "return", "turn_l", "turn_r", "power"],
    "heat": ["hidden", "emerge", "idle", "walk", "charge", "skid", "attack_a", "attack_b", "roar", "return", "turn_l",
             "turn_r", "move"],
    "tide": ["hidden", "emerge", "idle", "move", "attack_a", "attack_b", "attack_c", "roar", "return", "turn_l", "turn_r"],
    "air": ["hidden", "emerge", "idle", "move", "glide", "flutter", "stoop", "attack_a", "attack_b", "roll", "flare", "return",
            "turn_l", "turn_r"],
}
OWN = ("hidden", "emerge", "return")

SND = {"nature": {"step": "clatter", "call": "echo", "bellow": "echo", "strain": "echo", "groan": "echo", "lash": "sweep"},
       "heat": {"step": "clatter", "snarl": "echo", "roar": "echo", "bellow": "echo", "skid": "skid"},
       "tide": {"step": "clatter", "click": "clatter", "sweep": "sweep", "swing": "sweep", "flare": "flare", "roar": "echo"},
       "air": {"flap": "clatter", "rattle": "clatter", "slash": "sweep", "shriek": "echo", "chirr": "echo", "flare": "sweep",
               "land": "clatter"}}
PRT = {"nature": {"dust": "bonedust", "rock": "rock", "leaf": "moss", "pollen": "moss"},
       "heat": {"scorch": "haze", "haze": "haze", "step": "bonedust", "horn": "ember", "vent": "ember", "spark": "ember",
                "ember": "ember", "skid": "bonedust"},
       "tide": {"spray": "frost", "flake": "frost", "glint": "glint", "splinter": "shard", "mist": "frost"},
       "air": {"trail": "feather"}}
DISPLAY = {"nature": "Fossil Titanosaur", "heat": "Fossil Carnotaur", "tide": "Fossil Spinosaur", "air": "Fossil Microraptor"}
BOUNDS = {"nature": (64, 44, (0, 8, 0)), "heat": (40, 24, (0, 4, 0)), "tide": (44, 26, (0, 4, 0)), "air": (36, 24, (0, 3, 0))}
DENSITY = {"nature": 1.0, "heat": 1.0, "tide": 1.2, "air": 1.6}


def skeleton_model(sp):
    m = Model(f"ed5_skel_{sp}", density=DENSITY[sp], bounds=BOUNDS[sp])
    Sk(sp, m, Mats(sp))
    return m


def skeleton_anims(sp):
    names = [n for n in STATES[sp] if n not in OWN]
    anims = reuse(sp, names, SND[sp], PRT[sp])
    return [hidden_anim(), emerge_anim(sp), return_anim(sp), rattle_anim(sp)] + anims


def actor_maps(sp):
    snd = {"clatter": f"grimoire.ed5_clatter_{sp}", "echo": f"grimoire.ed5_echo_{sp}", "peel": "grimoire.ed5_peel",
           "sweep": "grimoire.ed5_sweep", "settle": "grimoire.ed5_settle"}
    if sp == "heat":
        snd["skid"] = "grimoire.ed5_skid"
    if sp == "tide":
        snd["flare"] = "grimoire.ed5_icecrack"
    prt = {k: f"grimoire:ed5_{k}" for k in {"bonedust", *PRT[sp].values()}}
    return snd, prt


def build(pack):
    for sp in SPECIES:
        m = skeleton_model(sp)
        anims = skeleton_anims(sp)
        snd, prt = actor_maps(sp)
        states = {i: [n] for i, n in enumerate(STATES[sp])}
        pack.actor(f"ed5_skel_{sp}", m, anims, states, always=["rattle"], scale=LIVING[sp].SCALE, lifetime=60,
                   sounds=snd, particles=prt, display=DISPLAY[sp], blend=0.25)
        by = {a.name: a for a in anims}
        r = relief(sp)
        print(f"    ed5_skel_{sp}: {m.cube_count()} cubes, {len(m.order)} bones, tex {m.tex_size}, relief s={r['s']:.3f} "
              f"f={r['f']:.3f}")
        rt = (by["rattle"], 0.5)
        if sp == "nature":
            poses = [[(by["idle"], 0.0), rt], [(by["attack_a"], 1.9), rt], [(by["attack_b"], 1.35), rt]]
        elif sp == "heat":
            poses = [[(by["idle"], 0.0), rt], [(by["charge"], 0.3), rt], [(by["attack_a"], 0.6), rt]]
        elif sp == "tide":
            poses = [[(by["idle"], 0.0), rt], [(by["attack_a"], 0.5), rt], [(by["attack_c"], 0.45), rt]]
        else:
            poses = [[(by["glide"], 0.0), rt], [(by["idle"], 0.5), rt], [(by["move"], 0.3), rt]]
        pack.preview(f"ed5_skel_{sp}_a", m, poses, views=((-90, 6), (35, 18), (0, 80)), cell=(420, 360))
        E, R = EMERGE_LEN[sp], RETURN_LEN[sp]
        pack.preview(f"ed5_skel_{sp}_b", m, [(by["emerge"], 0.0), (by["emerge"], 0.7), (by["emerge"], E * 0.55),
                                             (by["emerge"], E), (by["return"], R * 0.6)],
                     views=((0, 0), (-90, 6)), cell=(300, 300))
