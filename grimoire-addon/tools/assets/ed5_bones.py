def geo_nature(sk):
    mt, d, P = sk.mt, sk.d, sk.P
    # dorsal series + ribcage
    for z, bn in ((-44, "chest"), (-36, "chest"), (-28, "chest"), (-20, "chest"), (-12, "chest"), (-4, "body"), (4, "body"),
                  (12, "body")):
        vertebra(sk, bn, (0, 66, z - 3.8), (0, 66, z + 3.8), 7.5, trans=8.5)
    for z, bn, bot in ((-38, "chest", 32), (-30, "chest", 30), (-22, "chest", 30), (-14, "chest", 31), (-6, "body", 33),
                       (2, "body", 35), (10, "body", 39)):
        rib(sk, bn, z, 65.5, 25.5 if z > -36 else 23, bot, 12.5, thick=2.3, sweep=4.5)
    for sx in (1, -1):
        sk.rod("chest", (sx * 21, 71, -25), (sx * 25.5, 41, -37), 2.4, 9.5, mt.bone2)            # scapula
        sk.box("chest", (sx * 23, 38.5, -39.5), (3, 6, 8), mt.bone)                             # coracoid
        if d:
            sk.box("chest", (sx * 6.5, 32.5, -32), (8, 2, 11), mt.bone2)                        # sternal plates
    # pelvis
    sk.rod("hips", (0, 66, 14.5), (0, 66, 42.5), 8.5, 8, mt.bone)                               # sacrum
    sk.rod("hips", (0, 71, 17), (0, 71, 40), 2.2, 8, mt.bone2)                                   # fused sacral spines
    for sx in (1, -1):
        sk.rod("hips", (sx * 13, 66, 12.5), (sx * 14.5, 63.5, 43.5), 3.0, 15, mt.bone)            # ilium blade
        sk.rod("hips", (sx * 13, 58, 24), (sx * 9.5, 35, 15.5), 3.6, 4.4, mt.bone, variant=1)       # pubis
        sk.rod("hips", (sx * 13, 58, 34), (sx * 8.5, 40, 46), 3.0, 3.6, mt.bone, variant=2)         # ischium
    # bifid neural spines (the strata crest bones) with moss cushions
    for r in sk.info["ridges"]:
        x, y, z = P(r)
        y = min(y, 72.0)
        for sx in (1, -1):
            sk.rod(r, (sx * 1.1, y - 4.5, z), (sx * 4.2, y + 5.5, z + 1.5), 1.8, 3.4, mt.bone2)
        sk.box(r, (0, y + 5.5, z + 1.2), (10, 3.2, 6.5), mt.moss, variant=int(z) % 3)
    # moss sprigs on the ribs (tree bones) and hanging moss curtains
    for k, tr in enumerate(sk.info["trees"]):
        x, y, z = P(tr)
        c = (x * 0.9, 65.5 + (k % 3), z)
