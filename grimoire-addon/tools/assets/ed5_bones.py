def _spread(names, total, weights=None, axis=0):
    w = weights or [1.0] * len(names)
    out = {}
    for n, k in zip(names, w):
        v = [0.0, 0.0, 0.0]
        v[axis] = total * k / sum(w)
        out[n] = tuple(v)
    return out


