def bone_tex(base=IVORY, stain=AMBER, mineral=MINERAL, glow=0.0, stain_amt=0.75, lines=True, key="b5bone", tint=None,
             tint_amt=0.0):
    """Bone ivory with amber / mineral staining, growth lines, pores and a bevel."""
    kb, ks, km = tex.rgb(base), tex.rgb(stain), tex.rgb(mineral)
    kt = tex.rgb(tint) if tint else None

    def fn(ctx):
        ix, iy = tex.px(ctx)
        v = ctx.variant
        n = tex.fbm(ix / 3.2 + v * 7.3, iy / 4.6 + v * 1.7, 401)
        n2 = tex.fbm(ix / 1.7 + 40 + v * 3.1, iy / 1.9, 402)
        t = tex.tile(ctx, base, 1.0, glow)
        col = tex.mix(kb, ks, (np.clip((n - 0.42) * 2.4, 0, 1) * stain_amt)[..., None])
        col = tex.mix(col, km, (np.clip((n2 - 0.68) * 5, 0, 1) * 0.55)[..., None])
        if lines and ctx.w >= 3:
            col = np.where((((ix + iy // 3) % 4) == 0)[..., None], col * 0.92, col)
        col = np.where((ctx.rng.random((ctx.h, ctx.w)) < 0.05)[..., None], col * 0.72, col)
        if kt is not None:
            col = tex.mix(col, kt, tint_amt)
        t[..., :3] = col
        return tex.bevel(ctx, tex.grain(ctx, t, 0.045), 0.2)
    return Mat(fn, f"{key}{base}{stain}{mineral}{glow}{stain_amt}{lines}{tint}{tint_amt}")


def vane_tex(color, edge, a=0.42, key="b5vane", rachis="#ffffff"):
    """Translucent spectral feather vane (blend): quill at the tile top, denser toward the tip."""
    base = tex.feather(color, edge, rachis, glow=0.0, notch=0.14)

    def fn(ctx):
        t = np.array(base.fn(ctx), dtype=float)
        inside = t[..., 3] > 0.5
        ix, iy = tex.px(ctx)
        al = np.where(inside, a * (0.55 + 0.75 * ctx.V), 0.0)
        mid = np.abs(ix - (ctx.w - 1) / 2) < 0.75
        al = np.where(inside & mid, min(1.0, a + 0.4), al)
        barb = inside & (((iy + np.abs(ix - (ctx.w - 1) / 2).astype(int)) % 3) == 0)
        al = np.where(barb, np.clip(al + 0.15, 0, 1), al)
        t[..., 3] = np.clip(al, 0, 1)
        return t
    return Mat(fn, f"{key}{color}{edge}{a}", mode="blend")


def membrane_tex(color, vein, a=0.2, key="b5memb"):
    """Ghostly reconstructed sail membrane (blend) with frost veins."""
    kc, kv = tex.rgb(color), tex.rgb(vein)

    def fn(ctx):
        ix, iy = tex.px(ctx)
        t = tex.tile(ctx, color, a, 0.0)
        n = tex.fbm(ix / 3.0 + ctx.variant * 5, iy / 3.0, 451)
        vein_m = np.abs(np.sin(ix * 0.9 + n * 6.0)) < 0.18
        t[..., :3] = np.where(vein_m[..., None], kv, tex.mix(kc, kv, ctx.V[..., None] * 0.4))
        t[..., 3] = np.where(vein_m, a + 0.3, a * (0.5 + 0.7 * (1 - ctx.V)))
        t[..., 3] = np.where(ctx.V > 0.94, 0.0, t[..., 3])
        return t
    return Mat(fn, f"{key}{color}{vein}{a}", mode="blend")


