# ================================================================ builder
class Sk:
    """Recreates the living rig (same names / pivots / parents) and adds bone geometry to it.

    s, t: uniform scale and offset applied to every point (reliefs); pose: extra bind rotations
    (death pose); detail 0 drops teeth, claws, processes and sinews (reliefs)."""

    def __init__(self, sp, model, mats, prefix="", parent=None, s=1.0, t=(0, 0, 0), pose=None, detail=1, locators=True):
        self.sp, self.m, self.mt = sp, model, mats
        self.lm, self.info = living(sp)
        self.pre, self.s, self.t, self.d = prefix, float(s), np.array(t, dtype=float), detail
        pose = pose or {}
        for n in self.lm.order:
            b = self.lm.bones[n]
            par = (prefix + b.parent) if b.parent else parent
            dr = pose.get(n, (0, 0, 0))
            nb = model.bone(prefix + n, par, pivot=self.X(b.pivot), rot=tuple(b.rot[i] + dr[i] for i in range(3)))
            if locators:
                for k, v in b.locators.items():
                    nb.locator(k, self.X(v))
        GEO[sp](self)

    def X(self, p):
        return tuple(float(p[i]) * self.s + float(self.t[i]) for i in range(3))

    def P(self, n):
        return np.array(self.lm.bones[n].pivot, dtype=float)

    def B(self, n):
        return self.m.bones[self.pre + n]

    def box(self, n, c, size, mat, rot=None, pivot=None, variant=0):
        self.B(n).box(self.X(c), tuple(abs(float(x)) * self.s for x in size), mat, rot=rot,
                      pivot=self.X(pivot) if pivot is not None else None, variant=variant)

    def rod(self, n, p0, p1, w, h=None, mat=None, variant=0, shrink=0.0):
        p0, p1 = np.array(p0, dtype=float), np.array(p1, dtype=float)
        d = p1 - p0
        L = float(np.linalg.norm(d))
        if L < 1e-6:
            return
        u = d / L
        if shrink:
            p0, p1, L = p0 + d * shrink, p1 - d * shrink, L * (1 - 2 * shrink)
        rx = -math.degrees(math.asin(max(-1.0, min(1.0, u[1]))))
        ry = math.degrees(math.atan2(u[0], u[2])) if abs(u[1]) < 0.999 else 0.0
        c = (p0 + p1) / 2
        self.box(n, c, (w, h if h is not None else w, L), mat or self.mt.bone, rot=(round(rx, 3), round(ry, 3), 0), pivot=c,
                 variant=variant)

    def copy_planes(self, n, mat):
        """Reproduce the living bone's cubes (feather / fin sheets) with another material."""
        for c in self.lm.bones[n].cubes:
            self.B(n).cube(self.X(c.origin), tuple(x * self.s for x in c.size), mat, rot=c.rot,
                           pivot=self.X(c.pivot) if c.pivot else None, faces=c.faces, variant=c.variant)


# ---------------------------------------------------------------- anatomy helpers
def vertebra(sk, n, p0, p1, w, spine=0.0, chev=0.0, trans=0.0, tilt=0.35, sinew=True, mat=None, gap=0.09):
    p0, p1 = V(*p0), V(*p1)
    d = p1 - p0
    L = float(np.linalg.norm(d))
    u = d / L
    sk.rod(n, p0, p1, w, w * 0.92, mat or sk.mt.bone, shrink=gap, variant=int(abs(p0[2])) % 3)
    mid = (p0 + p1) / 2
    if spine > 0.4:
        top = mid + UP * (w * 0.4)
        sk.rod(n, top, top + UP * spine + u * spine * tilt, max(0.7, w * 0.26), L * 0.45, sk.mt.bone2)
    if chev > 0.4 and sk.d:
        bot = mid - UP * (w * 0.4)
        sk.rod(n, bot, bot - UP * chev + u * chev * 0.45, max(0.6, w * 0.22), L * 0.32, sk.mt.bone2)
    if trans > 0.4 and sk.d:
        sk.rod(n, mid - XA * trans, mid + XA * trans, L * 0.3, max(0.6, w * 0.22), sk.mt.bone)
    if sinew and sk.d:
        sk.rod(n, p0 + UP * w * 0.5, p1 + UP * w * 0.5, 0.55 + w * 0.04, 0.55 + w * 0.04, sk.mt.sinew)


def rib(sk, n, z, top_y, half_w, bot_y, belly_w, thick=1.6, sweep=0.0, x0=2.0, mat=None):
    for sx in (1, -1):
        a = V(sx * x0, top_y, z)
        b = V(sx * half_w * 0.86, top_y - (top_y - bot_y) * 0.13, z + sweep * 0.3)
        c = V(sx * half_w, top_y - (top_y - bot_y) * 0.56, z + sweep * 0.7)
        d = V(sx * belly_w, bot_y, z + sweep)
        pts = [a, b, c, d] if sk.d else [a, b, d]
        for p, q in zip(pts, pts[1:]):
            sk.rod(n, p, q, thick, thick * 1.25, mat or sk.mt.bone, variant=1)


def long_bone(sk, n, p0, p1, w, head=None, knob=1.4, sinew_off=None):
    p0, p1 = V(*p0), V(*p1)
    sk.rod(n, p0, p1, w, w, sk.mt.bone, shrink=0.04, variant=2)
    if sk.d:
        sk.box(n, p1 + (p0 - p1) * 0.06, (w * knob, w * knob * 0.8, w * knob), sk.mt.bone2)
        if head is not None:
            sk.box(n, head, (w * 1.15,) * 3, sk.mt.bone2)
        if sinew_off is not None:
            o = V(*sinew_off)
            sk.rod(n, p0 + o, p1 + o, 0.6, 0.6, sk.mt.sinew)


def claw(sk, n, base, tip, w):
    base, tip = V(*base), V(*tip)
    if not sk.d:
        sk.rod(n, base, tip, w * 0.8, w, sk.mt.claw)
        return
    mid = base + (tip - base) * 0.55 + UP * 0.12 * float(np.linalg.norm(tip - base))
    sk.rod(n, base, mid, w, w * 1.2, sk.mt.claw)
    sk.rod(n, mid, tip, w * 0.55, w * 0.7, sk.mt.claw)


def eye(sk, n, c, size, sx):
    sk.box(n, (sx * c[0], c[1], c[2]), size, sk.mt.dark)
    sk.box(n, (sx * (c[0] + size[0] * 0.22), c[1], c[2]), (size[0] * 0.75, size[1] * 0.36, size[2] * 0.36), sk.mt.eye)


