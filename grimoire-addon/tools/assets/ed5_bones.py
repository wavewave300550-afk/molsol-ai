# ================================================================ posed geometry / relief numbers
def posed_quads(model, names=None, pose=None):
    """[(4x3 corners)] of every painted face in a pose, without texturing the model."""
    mats = model.bone_matrices(pose)
    out = []
    for n in model.order:
        if names is not None and n not in names:
            continue
        bm = mats[n]
        for c in model.bones[n].cubes:
            m = bm
            if c.rot:
                m = bm @ _trs(c.pivot or tuple(c.origin[i] + c.size[i] / 2 for i in range(3)), c.rot)
            for f in c.paint_faces():
                q = np.array([list(p) + [1.0] for p in c.corners(f)])
                out.append((m @ q.T).T[:, :3])
    return out


_REL = {}


def flat_vec(sp, k=None):
    k = FLAT[sp] if k is None else k
    v = [1.0, 1.0, 1.0]
    v[FLAT_AXIS[sp]] = k
    return tuple(v)


def relief(sp):
    """Numbers that line a skeleton up with its relief.

    s     uniform model->tablet scale of the relief      C  death-pose centre in skeleton model units
    f     root scale of an emerging skeleton (= s / SCALE)
    pos0  root position (model units) that puts the flattened, posed skeleton centre on the entity origin
    """
    if sp in _REL:
        return _REL[sp]
    tmp = Model(f"ed5_tmp_{sp}")
    Sk(sp, tmp, Mats(sp), detail=0, locators=False)
    quads = posed_quads(tmp, pose={n: (r, (0, 0, 0), (1, 1, 1)) for n, r in DEATH[sp].items()})
    pts = np.concatenate(quads)
    R = rot_matrix(*REL_ROT[sp])
    S = np.diag(flat_vec(sp))
    pt = (R @ S @ pts.T).T
    lo, hi = pt.min(axis=0), pt.max(axis=0)
    ct = (lo + hi) / 2
    pw, ph = PANEL[1] - PANEL[0], PANEL[3] - PANEL[2]
    s = min(pw / (hi[0] - lo[0]), ph / (hi[1] - lo[1]))
    C = np.linalg.inv(R @ S) @ ct
    scale = LIVING[sp].SCALE
    f = s / scale
    Ra = rot_matrix(*ACT_ROT[sp])
    ry180 = rot_matrix(0, 180, 0) if YAW_OFF[sp] == 180 else np.eye(3)
    assert np.allclose(Ra, ry180 @ R, atol=1e-6), f"{sp}: actor / relief rotations disagree"
    pos0 = -(Ra @ (f * S) @ C)
    _REL[sp] = dict(s=float(s), C=C, f=float(f), pos0=tuple(float(x) for x in pos0), ext=(hi - lo) * s, scale=scale)
    return _REL[sp]


# ================================================================ animation helpers
def reuse(sp, names, snd, prt):
    """Copies of the living species' plain bone animations; sound / particle events are remapped to
    this skeleton's own short names (events without a mapping are dropped)."""
    lm, info = living(sp)
    src = {a.name: a for a in LIVING[sp].build_anims(info)}
    out = []
    for n in names:
        a = copy.deepcopy(src[n])
        a.model = None
        a.sounds = {t: [snd[e] for e in es if e in snd] for t, es in a.sounds.items()}
        a.sounds = {t: es for t, es in a.sounds.items() if es}
        a.particles = {t: [(prt[e], loc, sc) for (e, loc, sc) in es if e in prt] for t, es in a.particles.items()}
        a.particles = {t: es for t, es in a.particles.items() if es}
        out.append(a)
    return out


def _lerp3(a, b, f):
    return tuple(a[i] + (b[i] - a[i]) * f for i in range(3))


def _scale3(v, k):
    return tuple(x * k for x in v)


