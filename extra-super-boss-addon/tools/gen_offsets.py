#!/usr/bin/env python3
"""
Measures where the gauntlet palm, chest and head really are at the moments the scripts need them
(read from the generated geometry + animations through tools/kinematics.py) and writes
scripts-src/offsets.ts.  Offsets are in blocks in the boss's local frame: fwd (in front),
up, left (his left), already multiplied by the client render scale.
"""
from __future__ import annotations

import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import kinematics as K  # noqa: E402
import preview_sheets as PS  # noqa: E402
import render_preview as R  # noqa: E402
import spec  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SCALE = json.load(open(os.path.join(ROOT, "balance.json")))["boss"]["render_scale"]


def loc(pose, bone, name):
    x, y, z = K.locator_world(R.GEO, pose, bone, name)
    return {"fwd": round(-z * SCALE / 16, 3), "up": round(y * SCALE / 16, 3), "left": round(x * SCALE / 16, 3)}


def main():
    m = {k: v["moments"] for k, v in spec.ACTIONS.items()}
    out = {}
    shots = [loc(PS.layered_pose("gear_volley", m["gear_volley"][s]), "ghand_l", "loc_palm") for s in ("shot1", "shot2", "shot3")]
    out["PALM_SHOT"] = {k: round(sum(s[k] for s in shots) / len(shots), 3) for k in ("fwd", "up", "left")}
    out["PALM_QUAKE"] = loc(PS.layered_pose("quake", m["quake"]["impact"]), "ghand_l", "loc_palm")
    out["PALM_DIVE"] = loc(PS.layered_pose("dive_strike", m["dive_strike"]["impact"], 2, "wings_swept"), "ghand_l", "loc_palm")
    out["CHEST"] = loc(PS.layered_pose(None, 0), "body", "loc_chest")
    out["HEAD"] = loc(PS.layered_pose(None, 0), "head", "loc_head")
    out["CORE"] = loc(PS.layered_pose(None, 0), "gauntlet_l", "loc_core")
    lines = ["// GENERATED by tools/gen_offsets.py from the geometry + animations - do not edit.",
             "/** Points on the boss in blocks, local frame: fwd = in front, up, left = his left. */",
             "export interface LocalOffset { fwd: number; up: number; left: number }"]
    for k, v in out.items():
        lines.append(f"export const {k}: LocalOffset = {json.dumps(v).replace(chr(34), '')};")
    p = os.path.join(ROOT, "scripts-src", "offsets.ts")
    with open(p, "w") as f:
        f.write("\n".join(lines) + "\n")
    for k, v in out.items():
        print(f"{k:11s} {v}")


if __name__ == "__main__":
    main()
