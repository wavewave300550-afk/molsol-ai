"""
Write TEST_REPORT.md from the result files of the last validator and simulation runs.

    python3 tools/validate.py --mct && node tools/sim/run.mjs && python3 tools/report.py

Numbers in the report are read from build/validate_results.json and
build/sim_results.json; nothing is typed in by hand. The verification-status
section is fixed text describing what this environment can and cannot check.
"""
from __future__ import annotations

import json
import os
import re
import sys
from collections import defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
NAMES = {"vesperra": "Vesperra", "cantor": "Cantor XIII", "nomos": "Nomos", "orison": "Orison"}


def mmss(s: float) -> str:
    return f"{int(s // 60)} min {int(round(s % 60)):02d} s"


def main() -> None:
    v = json.load(open(os.path.join(ROOT, "build", "validate_results.json")))
    sim = json.load(open(os.path.join(ROOT, "build", "sim_results.json")))
    seeds_path = os.path.join(ROOT, "build", "sim_seeds.json")
    seeds = json.load(open(seeds_path)) if os.path.exists(seeds_path) else None
    results, metrics = sim["results"], sim["metrics"]
    bosses = [k for k in NAMES if any(r["name"].startswith(k + ":") for r in results)]
    by_boss = defaultdict(list)
    for r in results:
        by_boss[r["name"].split(":")[0]].append(r)
    failed = [r for r in results if not r["ok"]]
    L = []
    w = L.append

    w("# The Abandoned Miracles — test report\n")
    w("This report is generated by `tools/report.py` from the output of the validator and the simulation. "
      "It states what was checked, how, and — just as importantly — what was not.\n")

    w("## 1. Verification status at a glance\n")
    w("| Area | Status | How |")
    w("|---|---|---|")
    w(f"| Pack files: syntax, cross-references, budgets | **verified** | `tools/validate.py`: {v['checks_passed']:,} checks, {v['checks_failed']} failed |")
    m = v.get("mct")
    if m:
        w(f"| Pack files against Mojang's schemas | **verified** | Minecraft Creator Tools 0.21.0 validator: {m['errors']} errors, {m['warnings']} warnings |")
    else:
        w("| Pack files against Mojang's schemas | not run in this build | run `python3 tools/validate.py --mct` |")
    w("| Script against the stable API surface | **verified** | TypeScript strict type-check against `@minecraft/server` 2.6.0 and `@minecraft/server-ui` 2.0.0 typings (the versions the manifest asks for) |")
    w(f"| Combat logic, state machine, cleanup, multiplayer rules | **verified in simulation** | {len(results) - len(failed)}/{len(results)} scenarios (shipped script bundle, strict Script API stand-in) |")
    w("| Loading in Minecraft | **partly observed on a real device** | the project owner opened builds 1.0.0 / 1.0.1 on iOS and sent the Content Log and a screenshot: "
      "entity, geometry, render-controller, animation-controller, particle, sound, item, recipe and structure files produced no errors; "
      "Vesperra's model and textures render; a Seal summons her; the summon line, the boss bar and the action-bar HUD appear |")
    w("| Animation, particles in motion, audio, combat in the game | **NOT VERIFIED** | in that session the game rejected all four animation files "
      "(see section 7); the fix in 1.0.2 has not been confirmed in the game |")
    w("| Performance on real devices | **NOT VERIFIED** | budgets and call counts only (section 6) |")
    w("| Play-feel, difficulty, 4–7 minute target with human players | **NOT VERIFIED** | simulated bot times only (section 5) |")
    w("")
    w("### Why nothing was run in the game by the build itself\n")
    w("* The only way to run Bedrock in this environment is Bedrock Dedicated Server through Minecraft Creator Tools. "
      "That requires accepting the Minecraft End User License Agreement, which the project owner must do personally "
      "(`npx -y @minecraft/creator-tools@0.21.0 eula`); it was not accepted on their behalf.")
    w("* No Minecraft client exists here, so nothing visual or audible could be observed in any case.")
    w("* Consequently **no screenshot in this repository is from the game.** Images under `docs/previews/` are produced by "
      "the project's own software renderer from the shipped geometry, textures and animation data.\n")
    w("### First things to check in a real game\n")
    w("1. Import the `.mcaddon`, enable both packs on a world, watch the Content Log while it loads.")
    w("2. `/abm:wake vesperra` on flat ground: model, textures, idle and walk; boss bar; action-bar line.")
    w("3. Does the boss walk and turn smoothly? If it jitters or does not move, switch *Stepwise boss movement* on in the Codex and report it.")
    w("4. Are floor telegraphs visible, flat on the ground and aligned with where damage lands? (`/abm:debug attack 1` … `7`)")
    w("5. `/abm:debug phase2` and `/abm:debug kill`: transformation and death sequences.")
    w("6. Damage taken in enchanted diamond versus the numbers in DESIGN_SPEC §3.5.")
    w("7. The same on a phone, watching frame rate during each boss's ultimate.\n")

    w("## 2. Static validation\n")
    w(f"`python3 tools/validate.py --mct` — **{v['checks_passed']:,} passed, {v['checks_failed']} failed.**\n")
    w("| Section | Passed | Failed |")
    w("|---|---:|---:|")
    for name, s in v["sections"].items():
        w(f"| {name} | {s['passed']:,} | {s['failed']} |")
    w("")
    w("What the sections cover: JSON syntax of every pack file; manifests (unique UUIDs, mutual dependencies, stable "
      "module versions, `min_engine_version`); the script bundle (only the two stable modules imported, no block-editing "
      "calls, no `runTimeout`); behaviour ↔ client entity pairs, properties, events and loot tables; geometry (bone "
      "hierarchy, UV bounds, cube/bone budgets); client entities (geometry, textures of the right size, materials, "
      "render controllers, animation maps, particle and sound aliases); animations (bones exist in the model, keyframes "
      "inside the animation length, timeline effects declared, locators exist, every Molang expression parses); "
      "animation controllers (targets exist, every state reachable, no dead ends); particles (emitter completeness, "
      "sprite sheet size, Molang); sounds (files exist, Ogg Vorbis, mono, no orphans); items, recipes and loot against "
      "the 1.26.60 vanilla catalogue; localization (names for every entity and item, every translation key the script "
      "can send); structures (NBT parses, sizes, palette, block names and states exist); packaging (archive integrity "
      "and exact equality with the pack folders); the test world (level.dat, embedded packs, kit functions).\n")
    if v["failures"]:
        w("Failures:\n")
        for f in v["failures"]:
            w(f"* {f}")
        w("")
    w("### Content summary\n")
    w("| | |")
    w("|---|---|")
    w(f"| Entities (behaviour + client) | {v['entities']} |")
    w(f"| Animations / animation controllers | {v['animations']} / {v['animation_controllers']} |")
    w(f"| Particle effects | {v['particles']} |")
    w(f"| Sound events | {v['sound_events']} ({v['audio_bytes'] / 1e6:.1f} MB of Ogg Vorbis) |")
    w(f"| Items | {v['items']} |")
    w(f"| Localization keys | {v['lang_keys']} |")
    pk = v.get("packaging") or {}
    if pk:
        w(f"| `The_Abandoned_Miracles.mcaddon` | {pk['files']} files, {pk['mcaddon_bytes'] / 1e6:.2f} MB |")
    tw = v.get("testworld")
    if tw:
        w(f"| `The_Abandoned_Miracles_Test_World.mcworld` | {tw['files']} files, {tw['bytes'] / 1e6:.2f} MB, arenas: {len(tw['arenas'])} |")
    w("")
    w("| Model | Bones | Cubes | Texture |")
    w("|---|---:|---:|---|")
    for gid, g in sorted(v["geometries"].items()):
        w(f"| `{gid}` | {g['bones']} | {g['cubes']} | {g['texture'][0]}×{g['texture'][1]} |")
    w("")
    w("| Structure | Size | Blocks | Palette |")
    w("|---|---|---:|---:|")
    for name, s in sorted((v.get("structures") or {}).items()):
        w(f"| `{name}` | {s['size'][0]}×{s['size'][1]}×{s['size'][2]} | {s['blocks']:,} | {s['palette']} |")
    w("")

    w("## 3. Simulation\n")
    w("`node tools/sim/run.mjs` loads the **shipped** `scripts/main.js` against a strict stand-in for the Script API "
      "(`tools/sim/mock-server.mjs`) and plays whole encounters with bots. The stand-in is deliberately unforgiving about "
      "everything that can be checked against the real pack files: entity identifiers, property names, types and ranges, "
      "entity events, particle identifiers and the Molang variables each particle reads, sound events, items, structures "
      "and loot tables must all exist; world-changing calls inside a before-event throw, as in the game; any attempt to "
      "modify a block fails the run.\n")
    w("It is a model, not Minecraft: it cannot show that the engine behaves as the model assumes (movement physics, "
      "event ordering, invulnerability frames, armour arithmetic).\n")
    w(f"**Result: {len(results) - len(failed)}/{len(results)} scenarios passed.**\n")
    if seeds:
        w(f"Repeated with {len(seeds['seeds'])} different random seeds: {seeds['passed']}/{seeds['total']} scenario runs passed.\n")
    w("| Boss | Scenarios | Passed |")
    w("|---|---:|---:|")
    for k in bosses:
        rs = by_boss[k]
        w(f"| {NAMES[k]} | {len(rs)} | {sum(1 for r in rs if r['ok'])} |")
    w("")
    if failed:
        w("Failures:\n")
        for r in failed:
            w(f"* `{r['name']}` — {r['note']}")
        w("")

    w("### 3.1 What every boss is put through\n")
    w("| Scenario | What it establishes |")
    w("|---|---|")
    rows = [
        ("summon on suitable ground", "one boss entity, Seal consumed, protected intro, no block changed"),
        ("summon refused on holes / low ceiling / unloaded chunks / water", "no entity, Seal kept, reason sent, no block changed"),
        ("second summon too close is refused", "encounters cannot overlap"),
        ("`/summon` entity is adopted", "command-spawned bosses get a managed encounter"),
        ("player damage model", "exact damage for no armour and enchanted diamond; creative immune; shields stop blockable hits only; hit interval; lethal hit uses the native path"),
        ("damage from outside the arena is ignored", "anti-cheese rule and environmental immunity"),
        ("P1/P2 attack 1–7 executes and can hit", "each of the 14 attack/phase combinations starts when chosen, resolves hazards, records its cooldown, and damages a stationary player in at least one of seven positions"),
        ("P1/P2 attack 1–7 is avoidable at walking speed", "a bot that sees only telegraphed hazards, reacts after 0.3 s and walks (no sprint, no jump) takes no damage from four starting positions"),
        ("full encounter loop (solo)", "INTRO → PHASE_1 → PHASE_TRANSITION → PHASE_2 → DEATH in order; Phase II begins exactly at the threshold; no damage during the transition; all seven attacks chosen by the AI; trophy and loot awarded; remnant despawns; nothing left on the timeline; no helper left; no damage after the end"),
        ("boss death during an attack", "killing the boss mid-ultimate cancels every pending strike"),
        ("stagger and cancellation cannot deadlock", "twelve forced attacks interrupted at varying points; the AI keeps working afterwards"),
        ("four players", "health scale ×2.35; highest-threat player becomes the focus; a death and a disconnect are handled; scale never shrinks; abandonment resets the fight and refunds the Seal"),
        ("a player joining mid-fight", "becomes a participant and raises the scale"),
        ("two encounters at once", "participants, hazards and cancellation stay separate"),
        ("unload and reload", "encounter released with nothing pending; re-adopted in the same phase with boss-specific state and health intact, no intro replay"),
        ("native death (/kill)", "cleanup still happens"),
        ("commands, codex, script events, arena placement", "every access path works; arena placement only after confirmation"),
    ]
    for a, b in rows:
        w(f"| {a} | {b} |")
    w("")

    w("### 3.2 Boss-specific scenarios\n")
    for k in bosses:
        generic = ("summon", "player damage model", "damage from outside", "attack ", "full encounter", "boss death during",
                   "stagger and cancellation", "four players", "a player joining", "two encounters", "unload and reload",
                   "native death", "commands, codex", "second summon", "/summon")
        spec = [r for r in by_boss[k] if not any(g in r["name"] for g in generic)]
        if not spec:
            continue
        w(f"**{NAMES[k]}**\n")
        for r in spec:
            mark = "pass" if r["ok"] else "FAIL"
            note = f" — {r['note']}" if r["note"] and r["ok"] else (f" — {r['note']}" if not r["ok"] else "")
            w(f"* {mark}: {r['name'].split(': ', 1)[1]}{note}")
        w("")

    w("### 3.3 The 28 attacks\n")
    w("| Boss | Phase | # | Attack | Executes and hits | Avoidable at walking speed |")
    w("|---|---|---:|---|---|---|")
    for k in bosses:
        for phase in (1, 2):
            for idx in range(1, 8):
                a = next((r for r in by_boss[k] if f"P{phase} attack {idx} executes" in r["name"]), None)
                b = next((r for r in by_boss[k] if f"P{phase} attack {idx} is avoidable" in r["name"]), None)
                name = (b["note"] if b and b["ok"] else (a["note"].split(":")[0] if a else "?"))
                w(f"| {NAMES[k]} | {'I' if phase == 1 else 'II'} | {idx} | {name} | {'pass' if a and a['ok'] else 'FAIL'}"
                  f"{(' — ' + a['note'].split(': ', 1)[1]) if a and a['ok'] and ': ' in a['note'] else ''} | {'pass' if b and b['ok'] else 'FAIL'} |")
    w("")

    w("## 4. Edge cases\n")
    w("| Case | Status | Evidence |")
    w("|---|---|---|")
    edge = [
        ("Single-player survival", "simulated", "full encounter loop"),
        ("Creative mode", "simulated", "creative players are targeted but never damaged (damage model scenario); commands and Seals work"),
        ("Two-player encounter", "simulated", "mid-fight join scenario"),
        ("Up to four players", "simulated", "four-player scenario"),
        ("Player death", "simulated", "four-player scenario; dead players stop being participants"),
        ("Player disconnection", "simulated", "four-player scenario"),
        ("Player rejoining", "simulated", "treated as a new participant (mid-fight join scenario); per-player timers are cleared on leave"),
        ("Boss death during an attack", "simulated", "dedicated scenario"),
        ("Chunk unloading", "simulated", "unload/reload scenario (entity becomes invalid, then loads again)"),
        ("World save and reload", "simulated in part", "the same re-adoption path is used after a restart; a real save/quit/load was not performed"),
        ("Encounter cancellation", "simulated", "`/abm:dismiss`, Codex and script-event paths"),
        ("Multiple concurrent encounters", "simulated", "two-encounter scenario"),
        ("Running away from an active arena", "simulated", "abandonment in the four-player scenario; outside-damage scenario"),
        ("Lower-end mobile performance", "NOT VERIFIED", "see section 6 for the budgets that were enforced instead"),
    ]
    for a, b, c in edge:
        w(f"| {a} | {b} | {c} |")
    w("")

    w("## 5. Balance figures from simulation\n")
    w("One bot with a 13-damage weapon (about a Sharpness V diamond sword), swinging every 12 ticks whenever it is in "
      "reach, wearing enchanted diamond, dodging with full knowledge of telegraphs. A real player will land fewer hits "
      "and take more; these are lower bounds on fight length, not predictions.\n")
    w("| Boss | Time to defeat | Hits taken by the bot | Bot deaths | Swings landed |")
    w("|---|---|---:|---:|---:|")
    for k in bosses:
        mt = metrics.get(k)
        if mt:
            w(f"| {NAMES[k]} | {mmss(mt['soloSeconds'])} | {mt['hitsTaken']} | {mt['soloDeaths']} | {mt['landed']}/{mt['swings']} |")
    w("")
    w("Attack usage by the AI during those fights:\n")
    for k in bosses:
        mt = metrics.get(k)
        if mt:
            w(f"* {NAMES[k]}: " + ", ".join(f"{a} ×{n}" for a, n in sorted(mt["attacksUsed"].items())))
    w("")

    w("## 6. Performance\n")
    w("Not measured on any device. What was done instead:\n")
    w("* **Budgets enforced by the validator**: ≤ 480 cubes and ≤ 120 bones per model, textures ≤ 512², steady particle "
      "emitters ≤ 600 particles, audio ≤ 12 MB, mono clips.")
    w("* **No per-tick world scans**: participants come from one bounded player query per encounter every 5 ticks; "
      "orphan sweeps run every 10 s on tagged entities only; arena scans happen once per summon.")
    w("* **Bounded state**: one timeline per encounter; helper entities capped at 12 per encounter; all per-player data "
      "cleared on leave and at encounter end.")
    w("* **Counts observed in the simulated solo fights** (script calls, not rendered particles — one call may draw a "
      "whole line or arc on the client):\n")
    w("| Boss | Peak particle calls in one tick | Total particle calls | Peak live entities (boss + helpers) |")
    w("|---|---:|---:|---:|")
    for k in bosses:
        mt = metrics.get(k)
        if mt:
            w(f"| {NAMES[k]} | {mt['maxParticlesPerTick']} | {mt['particles']:,} | {mt['maxEntities']} |")
    w("")
    w("Risks to watch on low-end phones: the ultimates draw the most telegraph geometry at once; the *Reduced decorative "
      "particles* setting halves decoration but (by design) not telegraphs.\n")

    w("## 7. Known issues and limitations\n")
    issues = [
        "**Found on a real device and fixed in 1.0.2 (fixes not yet confirmed in the game):** "
        "(1) each boss had a sound-only footstep animation with an empty `bones` object; the game's schema requires at least one bone, "
        "and it then discarded *every* animation in the same file, so all four bosses stood frozen and the log filled with "
        "\"can't find animation\". (2) The test world's tick function used the score holder `#t`, which `execute if score` does not parse; "
        "one bad line unloads the whole function, so the arenas were never built and nothing was handed out. "
        "(3) The custom command `abm:summon` made the game warn that the alias `summon` is taken; it is now `abm:wake`. "
        "(4) The boss bar read \"Unknown\": `minecraft:boss` now carries the name. "
        "None of the four was caught by the project's validator, by Minecraft Creator Tools or by the simulation; the validator and the simulator now have a rule for each.",
        "Apart from that one session, nothing has been observed in Minecraft. Any of the assumptions the simulation makes about the engine could be wrong; "
        "the most consequential are script-driven movement (velocity impulses and `setRotation` on a mob without AI goals), "
        "the timing of `beforeEvents.entityHurt` relative to invulnerability frames, and flat-on-floor particle rendering.",
        "Player absorption hearts are bypassed by hazard damage (the Script API does not expose them).",
        "Hazards assume a level arena floor. On uneven ground telegraphs are drawn at the summoning height and may sink into or float above terrain.",
        "Health scaling for multiple players follows the brief's formula, but Bedrock's half-second hurt immunity means several "
        "players do not add damage linearly; four-player fights may run long until tuned with real players.",
        "Blockbench `.bbmodel` files are generated to Blockbench's project format but have not been opened in Blockbench here.",
        "The test world builds its arenas with commands during the first seconds after it is opened; this has not been observed in game.",
        "Minecraft Creator Tools' `export world` command rewrites pack manifests in place. It is not used by the build; do not run it against `packs/`.",
    ]
    extra = os.path.join(ROOT, "docs", "known_issues.txt")
    if os.path.exists(extra):
        issues += [ln.strip() for ln in open(extra, encoding="utf-8") if ln.strip()]
    for i in issues:
        w(f"* {i}")
    w("")
    w("## 8. Reproducing\n")
    w("```\nnpm install\nnpm run typecheck\nnpm run build            # packs/, dist/*.mcaddon, assets/blockbench/\npython3 tools/testworld.py\n"
      "python3 tools/validate.py --mct\nnode tools/sim/run.mjs     # add --seed N to vary\npython3 tools/report.py    # this file\n```\n")
    with open(os.path.join(ROOT, "TEST_REPORT.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(L))
    print(f"[report] TEST_REPORT.md written: {len(results)} scenarios, {len(failed)} failed, {v['checks_passed']} static checks")


if __name__ == "__main__":
    main()
